#!/usr/bin/env node
// Prepares the web demo for Azure Static Web Apps (and for `npm run web`):
//  1. copies src/ and data/ into api/lib/ so the Functions API ships the same adapters
//     and scenarios as the CLI (the API folder is deployed on its own);
//  2. writes web/fallback.json: mock-mode output the page shows when the live model is
//     not configured, throttled or down. Labelled MOCK in the UI, no latency shown.
// Cross-platform (Node only). Run after changing anything in src/ or data/.
import { cpSync, rmSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lib = join(root, "api", "lib");
rmSync(lib, { recursive: true, force: true });
mkdirSync(lib, { recursive: true });
cpSync(join(root, "src"), join(lib, "src"), { recursive: true });
cpSync(join(root, "data"), join(lib, "data"), { recursive: true });
writeFileSync(join(lib, "package.json"), JSON.stringify({ type: "module", private: true, description: "GENERATED by scripts/build-api.mjs from src/ and data/. Do not edit." }, null, 2) + "\n");

const { runScenario, SCENARIOS } = await import("../api/core.mjs");
const { mockDecisionProvider } = await import("../api/lib/src/providers/mock.js");
const mock = mockDecisionProvider({ MOCK_DECISION_MS: 0 });
const out = { mode: "mock", note: "Offline keyword stand-in, not a model. Latency is not shown because it would be simulated.", scenarios: {} };
for (const k of SCENARIOS) {
  const r = await runScenario(mock, k);
  for (const it of r.items) { it.ms = null; delete it.model; }
  delete r.wallMs; delete r.medianMs; delete r.model;
  out.scenarios[k] = r;
}
writeFileSync(join(root, "web", "fallback.json"), JSON.stringify(out, null, 1) + "\n");
console.log("api/lib and web/fallback.json updated");
