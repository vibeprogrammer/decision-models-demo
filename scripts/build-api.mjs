#!/usr/bin/env node
// Prepares the web demo for Azure Static Web Apps (and for `npm run web`):
//  1. copies src/ and data/ into api/lib/ so the Functions API ships the same adapters
//     and scenarios as the CLI (the API folder is deployed on its own);
//  2. writes web/scenarios.json: the four use cases (items, questions, expected labels)
//     the page shows before anything runs.
// Measured results the page shows before a live run come from web/recorded.json, written
// by `node scripts/record.mjs <site-url>` from a real run (no simulated numbers anywhere).
// Cross-platform (Node only). Run after changing anything in src/ or data/.
import { cpSync, rmSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lib = join(root, "api", "lib");
rmSync(lib, { recursive: true, force: true });
mkdirSync(lib, { recursive: true });
cpSync(join(root, "src"), join(lib, "src"), { recursive: true });
cpSync(join(root, "data"), join(lib, "data"), { recursive: true });
writeFileSync(join(lib, "package.json"), JSON.stringify({ type: "module", private: true, description: "GENERATED by scripts/build-api.mjs from src/ and data/. Do not edit." }, null, 2) + "\n");

const { catalog } = await import("../api/core.mjs");
writeFileSync(join(root, "web", "scenarios.json"), JSON.stringify(catalog(), null, 1) + "\n");
console.log("api/lib and web/scenarios.json updated");
